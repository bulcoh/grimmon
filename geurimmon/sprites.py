# 인덱스 1~15 = 흰색 → 검정 15단계 (SPRITE_GRAYS[인덱스-1]). 알이 너무 밋밋하면 여기 값만 조정.
SPRITE_GRAYS = [round(255 - i * 255 / 14) for i in range(15)]
BASE_COLOR = 1   # 기본 도형용 '옅은 흰색' = 16색 팔레트의 1번 인덱스(238)

def sprite_image(rows):
    from PySide6.QtGui import QImage, QColor
    img = QImage(32, 32, QImage.Format_ARGB32); img.fill(0)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != "0":
                v = SPRITE_GRAYS[int(c, 16) - 1]; img.setPixelColor(x, y, QColor(v, v, v))
    return img

def _square(s=14):
    o = 16 - s // 2
    return [y * 32 + x for y in range(o, o + s) for x in range(o, o + s)]
def _circle(r=7.8):
    return [y * 32 + x for y in range(32) for x in range(32) if (x + .5 - 16) ** 2 + (y + .5 - 16) ** 2 <= r * r]
def _triangle(base=16, h=23):
    out, y0 = [], (32 - h) // 2
    for k in range(h):
        w = max(1, round(base * (k + 1) / h)); x0 = 16 - w // 2
        out += [(y0 + k) * 32 + x for x in range(x0, x0 + w)]
    return out

SHAPES = {"원": _circle(), "네모": _square(), "세모": _triangle()}   # 픽셀 수 192 / 196 / 192
SHAPE_PIXELS = max(len(v) for v in SHAPES.values())
